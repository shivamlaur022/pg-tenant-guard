#!/usr/bin/env bash
# Builds the single-file installer dist/pg-tenant-guard.sql from sql/*.sql.
#
#   scripts/build.sh           write dist/pg-tenant-guard.sql
#   scripts/build.sh --check   exit 1 if the committed file is out of date
set -euo pipefail
export LC_ALL=C

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/dist/pg-tenant-guard.sql"

VERSION="$(sed -n "s/^as \$\$ select '\([0-9][0-9.]*\)' \$\$;\$/\1/p" "$ROOT/sql/001_schema.sql")"
if [[ -z "$VERSION" ]]; then
  echo "build.sh: could not read the version from sql/001_schema.sql" >&2
  exit 1
fi

render() {
  cat <<HEADER
-- pg-tenant-guard ${VERSION}
-- https://github.com/shivamlaur022/pg-tenant-guard
--
-- Generated by scripts/build.sh from sql/*.sql. Do not edit by hand.
--
-- Install:  psql "\$DATABASE_URL" -v ON_ERROR_STOP=1 -f pg-tenant-guard.sql
-- Supabase: paste into the SQL editor, or copy into a migration.
--
-- Runs in one transaction. Safe to run again on a database that already has
-- this version installed: objects are created with IF NOT EXISTS or
-- CREATE OR REPLACE, and seed rows use ON CONFLICT DO NOTHING.

begin;
HEADER
  for f in "$ROOT"/sql/*.sql; do
    printf '\n-- %s\n-- %s\n-- %s\n\n' \
      "------------------------------------------------------------------------" \
      "sql/$(basename "$f")" \
      "------------------------------------------------------------------------"
    cat "$f"
  done
  printf '\ncommit;\n'
}

if [[ "${1:-}" == "--check" ]]; then
  if ! diff -u "$OUT" <(render) >/dev/null 2>&1; then
    echo "dist/pg-tenant-guard.sql is out of date. Run: make dist" >&2
    diff -u "$OUT" <(render) | head -40 >&2 || true
    exit 1
  fi
  echo "dist/pg-tenant-guard.sql is up to date (v${VERSION})"
else
  mkdir -p "$(dirname "$OUT")"
  render > "$OUT"
  echo "Wrote dist/pg-tenant-guard.sql (v${VERSION})"
fi
